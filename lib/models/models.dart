// =============================================================================
// XAI DATA — Explainable AI payload returned by the ESP firmware
// =============================================================================
//
// The ESP embeds this inside /data and also serves it at /xai:
// {
//   "score": 0.72,       ← risk score 0.0–1.0
//   "level": "warning",  ← "ok" | "warning" | "critique"
//   "reason": "T=34C avertissement, hausse +1.2C/cycle"
// }
//
class XaiData {
  /// Risk score from 0.0 (safe) to 1.0 (critical)
  final double score;

  /// Level string: "ok" | "warning" | "critique"
  final String level;

  /// Human-readable explanation generated by the ESP firmware
  final String reason;

  const XaiData({
    required this.score,
    required this.level,
    required this.reason,
  });

  factory XaiData.fromJson(Map<String, dynamic> json) => XaiData(
    score:  (json['score'] as num?)?.toDouble() ?? 0.0,
    level:  json['level']  as String? ?? 'ok',
    reason: json['reason'] as String? ?? 'No explanation available.',
  );

  /// Fallback used when ESP does not return an xai object
  factory XaiData.empty() => const XaiData(
    score:  0.0,
    level:  'ok',
    reason: 'No XAI data available from the ESP.',
  );

  /// Display-ready level string (capitalised)
  String get levelDisplay {
    switch (level.toLowerCase()) {
      case 'critique': return 'Critical';
      case 'warning':  return 'Warning';
      default:         return 'OK';
    }
  }
}

// =============================================================================
// ENVIRONMENT DATA
// =============================================================================
class EnvironmentData {
  final double   temperature;
  final double   humidity;
  final bool     waterLeakDetected;
  final int      waterLevelRaw;
  final double   waterLevelPercent;
  final DateTime lastUpdated;
  final String   deviceId;
  final String   ipAddress;
  final EspAlerts alerts;

  /// XAI explanation from ESP firmware (never null — falls back to XaiData.empty())
  final XaiData xai;

  const EnvironmentData({
    required this.temperature,
    required this.humidity,
    required this.waterLeakDetected,
    required this.lastUpdated,
    this.waterLevelRaw     = 0,
    this.waterLevelPercent = 0.0,
    this.deviceId          = 'ESP8266-01',
    this.ipAddress         = '',
    this.alerts            = const EspAlerts(),
    XaiData? xai,
  }) : xai = xai ?? const XaiData(score: 0.0, level: 'ok', reason: 'parametres normaux');

  factory EnvironmentData.fromJson(Map<String, dynamic> json) {
    DateTime ts;
    try {
      ts = DateTime.parse(json['timestamp'] as String);
    } catch (_) {
      ts = DateTime.now();
    }

    return EnvironmentData(
      temperature:       (json['temperature']  as num).toDouble(),
      humidity:          (json['humidity']      as num).toDouble(),
      waterLeakDetected: json['water_leak']     as bool? ?? false,
      waterLevelRaw:     (json['water_level']   as num?)?.toInt()    ?? 0,
      waterLevelPercent: (json['water_percent'] as num?)?.toDouble() ?? 0.0,
      lastUpdated:       ts,
      deviceId:          json['device_id']      as String? ?? 'ESP8266-01',
      ipAddress:         json['ip']             as String? ?? '',
      alerts: json['alerts'] != null
          ? EspAlerts.fromJson(json['alerts'] as Map<String, dynamic>)
          : const EspAlerts(),
      // ── NEW: parse xai field ──────────────────────────────────────────────
      xai: json['xai'] != null
          ? XaiData.fromJson(json['xai'] as Map<String, dynamic>)
          : XaiData.empty(),
    );
  }

  factory EnvironmentData.mock() => EnvironmentData(
    temperature:       24.0,
    humidity:          45.0,
    waterLeakDetected: false,
    waterLevelRaw:     120,
    waterLevelPercent: 11.7,
    lastUpdated:       DateTime.now(),
    deviceId:          'ESP8266-01',
    ipAddress:         '192.168.1.104',
    xai: XaiData.empty(),
  );

  String get lastUpdatedText {
    final diff = DateTime.now().difference(lastUpdated);
    if (diff.inSeconds < 10) return 'À l\'instant';
    if (diff.inSeconds < 60) return 'Il y a ${diff.inSeconds}s';
    if (diff.inMinutes < 60) return 'Il y a ${diff.inMinutes}m';
    return 'Il y a ${diff.inHours}h';
  }
}

